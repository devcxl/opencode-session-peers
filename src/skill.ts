  "## Best practices",
  "",
  "- **List first, then address.** Re-list after a peer restarts or a scope changes; ids and titles",
  "  are not stable across recreations.",
  "- **Write self-contained messages.** The receiver sees your title and directory, not your",
  "  conversation. Include the task, constraints, file paths, and the expected outcome.",
  "- **Choose `send` unless you are blocked.** An `ask` reserves the only ask slot and keeps the",
  "  receiver on the hook; do not use it for progress or FYI messages.",
  "- **Batch related questions in one ask.** Structured interviews are not supported. Ask the peer",
  "  to answer point by point, and do not start a second ask while the first is waiting.",
  "- **For long work, use checkpoints.** Send a milestone report, then ask for a decision only when",
  "  one is actually needed; do not hold a ten-minute ask open over a long task.",
