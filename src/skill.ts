  "Avoid concurrent or mutual asks: the guards are best-effort and not atomic.",
  "",
  "### Answer a question",
  "",
  "A peer's question arrives with the sender's title and directory, and the line",
  '`To reply: peers({ action: "reply", ... })`. Answer with `reply`; do not reconstruct ids:',
  "",
  "```ts",
  'peers({ action: "reply", message: "Normalize them: strip the comma, keep the parse tree." })',
  "```",
  "",
  "If several peers are waiting, `reply` refuses and names the candidates. Run `pending`, then name",
