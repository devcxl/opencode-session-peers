/**
 * The model-facing text for the `peers` tool, registered as skills.
 *
 * The tool description says what each action does; the general skill says how
 * to use them together — which action fits which situation, what the delivery
 * and ask/reply rules forbid, and what each refusal means. It is loaded on
 * demand, so a session that never coordinates pays only for the description.
 *
 * The supervisor skill closes a different gap, the parent's (ADR-0002): a child
 * that asks a parked parent is told what happened by the refusal, but a parent
 * can only avoid the situation by choosing `background: true` when it spawns the
 * child — a decision made before any of this plugin's code runs. That is why it
 * stays a separate, narrowly described skill.
 */

