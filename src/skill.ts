  "| `E_ASK_IN_FLIGHT` | This session already has an outstanding ask. | Wait for its answer; do not open a second one. |",
  "| `E_MUTUAL_ASK` | The target has an open question to this session. | Answer it with `reply` first. |",
  "| `E_NO_PENDING_ASK` | No pending question matches the reply. | Run `pending`, then pass `replyTo` or `to`. |",
  "| `E_REPLY_AMBIGUOUS` | Several peers are waiting. | `pending`, then name `replyTo` (question id) or `to` (asker). |",
  "| `E_ASK_UNANSWERED` | This session holds an unanswered question, so a send to a third peer is refused. | Answer the asker first. |",
  "| `E_NO_ASK_TO_CANCEL` | No matching local ask wait is active in this instance. | Do not assume the question was withdrawn. |",
  "| `E_CANCEL_AMBIGUOUS` | More than one local wait matches. | Specify its question id with `replyTo`. |",
  "| `E_HANDOVER_*` | The handover shape was wrong: no goal, attachments, a reply reference, or an empty, incomplete, too long, or failed generation. | Fix the call; retry a failed generation. |",
  "",
