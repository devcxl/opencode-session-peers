  "## Actions at a glance",
  "",
  "| Action | Waits? | Use when |",
  "| --- | --- | --- |",
  "| `list` | no | Every live peer in this scope; always run it before addressing one. |",
  "| `list-cwd` | no | Only the peers in this session's directory. |",
  "| `send` | no | A message, report, or task that needs no answer. |",
  "| `ask` | yes | A decision or fact is needed before continuing. |",
  "| `reply` | no | Answer a pending question. |",
  "| `pending` | no | See who is waiting and get the question ids. |",
  "| `cancel` | no | Request a stop to an active local ask wait; the question is not withdrawn. |",
  "| `handover` | generation | Move the work to another session with a structured summary. |",
  "| `status` | no | This session's id, scope, and connectivity. |",
  "",
  "Messages carry inline attachments: `file` (whole file), `snippet` (excerpt, optional `language`),",
  "`context` (background). Each needs `name` and `content`; content is text, not a path.",
  "",
  "## Constraints that change how you work",
  "",
  "- **Same machine, same OS user.** There is no cross-machine transport and no peer authentication;",
  "  the trust boundary is the OS user. Never send secrets, tokens, or credentials.",
  "- **Same scope only.** Sessions in another scope are not peers. The configured default is",
  "  `default`; `/peers-scope <scope>` moves this session, and `status` shows the current one.",
  "- **No offline mailbox.** The plugin submits a message once; an unconfirmed outcome may have",
  "  been admitted. Check before retrying to avoid duplicates.",
  "- **A timeout is not cancellation.** After an `ask` times out, the question stays with the",
  "  recipient; a later answer is normally an ordinary message, but a racing reply can remain unread.",
  "- **Local cancellation.** `cancel` requests that this instance stop a wait; the question is not withdrawn",
  "  and the receiver may continue. A blocked session may not be able to call `cancel` itself; the",
  "  request and the ask's eventual cancelled result are distinct. Cross-instance cancellation is unavailable.",
  "- **Ask guards are not atomic.** Avoid a second outgoing ask or mutual asks, even if concurrent calls",
  "  happen to pass the checks. While holding an unanswered incoming ask, answer before sending to others.",
  "- **The recipient decides what it accepts.** Its `trigger` policy travels with its roster row:",
