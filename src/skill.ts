  "| `E_TARGET_REFUSES` / `E_TARGET_REPLIES_ONLY` / `E_TARGET_POLICY_UNKNOWN` | The recipient's `trigger` does not admit this message. | Use an ask only if it accepts replies; otherwise ask the user or another peer. |",
