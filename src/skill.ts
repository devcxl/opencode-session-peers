  "unknown status or policy is queued. Status can change between observation and submission.",
  "",
  "### Ask and wait",
  "",
  "Use `ask` when the answer changes what you do next:",
  "",
  "```ts",
  "peers({",
  '  action: "ask",',
  '  to: "ses_01J...",',
  '  message: "Should the parser reject trailing commas or normalize them? This decides the error-path tests.",',
  "})",
  "```",
  "",
  "The call blocks until the peer answers, the configured timeout passes (10 minutes by default), or",
