  "",
  "## Patterns",
  "",
  "### Delegate and continue",
  "",
  "Use `send` when the receiver does not need to answer before you continue:",
  "",
  "```ts",
  "peers({",
  '  action: "send",',
  '  to: "Write the tests",',
  '  message: "Task 2: add tests for the parser error paths. Files: test/parser.test.ts. Report when green.",',
  "  attachments: [",
  '    { type: "snippet", name: "failure.ts", language: "typescript", content: "..." },',
  "  ],",
  "})",
  "```",
  "",
  "A successful result means the host accepted the message, not that the receiver read it. The",
